window.RHAPSODE_THEME_BY_ID = Object.fromEntries(
  window.RHAPSODE_THEMES.map((theme) => [theme.id, theme])
);
window.RHAPSODE_THEME_ALIASES = { dark: "ink", light: "paper" };

window.applyRhapsodeTheme = function applyRhapsodeTheme(id) {
  const key = window.RHAPSODE_THEME_ALIASES[id] || id;
  const theme = window.RHAPSODE_THEME_BY_ID[key] || window.RHAPSODE_THEME_BY_ID.ink;
  const root = document.documentElement;
  for (const [name, value] of Object.entries(theme.colors)) {
    root.style.setProperty(`--${name}`, value);
  }
  root.dataset.theme = theme.id;
  root.dataset.mode = theme.mode;
  const meta = document.querySelector('meta[name="theme-color"]');
  if (meta) meta.content = theme.colors.bg;
  return theme;
};

window.rhapsodeFontStack = function rhapsodeFontStack(font) {
  if (!font || font === "sans") return "";
  if (font === "serif") {
    return '"New York", ui-serif, "Iowan Old Style", Palatino, Georgia, serif';
  }
  const family = String(font).replace(/["'\\;{}<>]/g, "").trim().slice(0, 80);
  if (!family) return "";
  return `"${family}", ui-sans-serif, -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif`;
};
